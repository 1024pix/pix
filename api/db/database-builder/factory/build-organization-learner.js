import _ from 'lodash';

import { databaseBuffer } from '../database-buffer.ts';
import { buildOrganization } from './build-organization.js';
import { buildUser } from './build-user.ts';

/**
 * @param {{
 *   id?: number,
 *   firstName?: string,
 *   preferredLastName?: string | null,
 *   lastName?: string,
 *   middleName?: string | null,
 *   thirdName?: string | null,
 *   sex?: string | null,
 *   birthdate?: string | null,
 *   birthCity?: string | null,
 *   birthCityCode?: string | null,
 *   birthCountryCode?: string | null,
 *   birthProvinceCode?: string | null,
 *   MEFCode?: string | null,
 *   status?: string | null,
 *   nationalStudentId?: string | null,
 *   nationalApprenticeId?: string | null,
 *   division?: string | null,
 *   studentNumber?: string | null,
 *   email?: string | null,
 *   educationalTeam?: string | null,
 *   department?: string | null,
 *   group?: string | null,
 *   diploma?: string | null,
 *   isDisabled?: boolean,
 *   createdAt?: Date,
 *   updatedAt?: Date,
 *   organizationId?: number,
 *   userId?: number | null,
 *   deletedBy?: number | null,
 *   deletedAt?: Date | null,
 *   isCertifiable?: boolean | null,
 *   certifiableAt?: Date | null,
 *   attributes?: Record<string, unknown> | null,
 * }} [attributes]
 */
const buildOrganizationLearner = function ({
  id = databaseBuffer.getNextId(),
  firstName = 'first-name',
  preferredLastName = 'pref-last-name',
  lastName = 'last-name',
  middleName = 'Gontran',
  thirdName = 'Dorothée',
  sex = 'M',
  birthdate = '2005-08-05',
  birthCity = 'Perpignan',
  birthCityCode = 'PERPICODE',
  birthCountryCode = '100',
  birthProvinceCode = '66',
  MEFCode = '10010012110',
  status = 'ST',
  nationalStudentId = null,
  nationalApprenticeId = null,
  division = '6eme',
  studentNumber = null,
  email = 'supermail@example.net',
  educationalTeam = 'Enseignants blonds',
  department = 'seine-et-troll',
  group = 'AB1',
  diploma = 'Licence',
  isDisabled = false,
  createdAt = new Date('2021-01-01'),
  updatedAt = new Date('2021-02-01'), // for BEGINNING_OF_THE_2020_SCHOOL_YEAR, can outdate very fast! ;)
  organizationId,
  userId,
  deletedBy = null,
  deletedAt = null,
  isCertifiable = null,
  certifiableAt = null,
  attributes = null,
} = {}) {
  organizationId = _.isUndefined(organizationId) ? buildOrganization().id : organizationId;
  userId = _.isUndefined(userId) ? buildUser().id : userId;

  const values = {
    id,
    lastName,
    preferredLastName,
    firstName,
    middleName,
    thirdName,
    sex,
    birthdate,
    birthCity,
    birthCityCode,
    birthCountryCode,
    birthProvinceCode,
    MEFCode,
    status,
    nationalStudentId,
    nationalApprenticeId,
    division,
    studentNumber,
    email,
    educationalTeam,
    department,
    group,
    diploma,
    isDisabled,
    createdAt,
    updatedAt,
    organizationId,
    userId,
    deletedBy,
    deletedAt,
    isCertifiable,
    certifiableAt,
    attributes,
  };

  return databaseBuffer.pushInsertable({
    tableName: 'organization-learners',
    values,
  });
};
export { buildOrganizationLearner };
